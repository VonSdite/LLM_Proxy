test('窄桌面首次进入自动收起，手动展开在区间内缩放和切页时保留', async ({ page }) => {
  const fixture = await mockAdmin(page)
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('/users')
  const sidebar = page.getByRole('complementary', { name: '侧边栏' })
  const expand = sidebar.getByRole('button', { name: '展开侧栏' })
  await expect(expand).toHaveAttribute('aria-expanded', 'false')
  for (const width of [1280, 1024, 901]) {
    await page.setViewportSize({ width, height: 800 })
    await expect(sidebar).toHaveCSS('width', '72px')
    expect((await page.locator('main').boundingBox())!.x).toBe(72)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await expand.click()
  await expect(sidebar.getByRole('button', { name: '收起侧栏' })).toHaveAttribute(
    'aria-expanded',
    'true',
  )
  await page.setViewportSize({ width: 1100, height: 800 })
  await expect(sidebar).toHaveCSS('width', '216px')
  await sidebar.getByRole('link', { name: '设置', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('系统设置')
  await expect(sidebar).toHaveCSS('width', '216px')
  expect(fixture.unexpected).toEqual([])
})

test('自动收起不覆盖宽屏手动选择，跨越断点保留页面草稿和节点', async ({ page }) => {
  const fixture = await mockAdmin(page)
  await page.setViewportSize({ width: 1440, height: 800 })
  await page.goto('/settings')
  const sidebar = page.getByRole('complementary', { name: '侧边栏' })
  await expect(sidebar).toHaveCSS('width', '216px')
  const input = page.getByRole('textbox', { name: '监听地址', exact: true })
  await input.fill('127.0.0.2')
  const inputNode = await input.elementHandle()
  await page.setViewportSize({ width: 1280, height: 800 })
  await expect(sidebar).toHaveCSS('width', '72px')
  await page.setViewportSize({ width: 1281, height: 800 })
  await expect(sidebar).toHaveCSS('width', '216px')
  await sidebar.getByRole('button', { name: '收起侧栏' }).click()
  await page.setViewportSize({ width: 1024, height: 800 })
  await expect(sidebar).toHaveCSS('width', '72px')
  await sidebar.getByRole('button', { name: '展开侧栏' }).click()
  await expect(sidebar).toHaveCSS('width', '216px')
  await page.setViewportSize({ width: 1440, height: 800 })
  await expect(sidebar).toHaveCSS('width', '72px')
  await page.setViewportSize({ width: 1024, height: 800 })
  await expect(sidebar).toHaveCSS('width', '72px')
  await expect(input).toHaveValue('127.0.0.2')
  expect(await input.evaluate((element, previous) => element === previous, inputNode)).toBe(true)
  expect(fixture.unexpected).toEqual([])
})

test('侧栏账户区在滚动后可见，收起后仍可切页、展开并退出', async ({ page }) => {
  const fixture = await mockAdmin(page)
  await page.setViewportSize({ width: 1440, height: 760 })
  await page.goto('/agents')
  const sidebar = page.getByRole('complementary', { name: '侧边栏' })
  const username = sidebar.getByText('admin', { exact: true })
  await expect(username).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
  const userBox = (await username.boundingBox())!
  expect(userBox.y).toBeGreaterThan(600)
  expect(userBox.y + userBox.height).toBeLessThan(760)
  const expanded = (await page.locator('main').boundingBox())!.x
  await sidebar.getByRole('button', { name: '收起侧栏' }).click()
  expect((await page.locator('main').boundingBox())!.x).toBeLessThan(expanded)
  await sidebar.getByRole('link', { name: '用户', exact: true }).click()
  await expect(page).toHaveURL(/\/users$/)
  await expect(sidebar.getByRole('link', { name: '用户', exact: true })).toHaveAttribute(
    'aria-current',
    'page',
  )
  const account = sidebar.getByRole('button', { name: 'admin 的账户菜单', exact: true })
  await account.click()
  const accountMenu = page.getByRole('menu', { name: '账户菜单', exact: true })
  await expect(accountMenu.getByRole('menuitem', { name: '退出登录' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(accountMenu).not.toBeVisible()
  await expect(account).toBeFocused()
  await sidebar.getByRole('button', { name: '展开侧栏' }).click()
  await expect(username).toBeVisible()
  await account.click()
  await accountMenu.getByRole('menuitem', { name: '退出登录' }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect(fixture.calls.filter((call) => call.path === '/api/logout')).toHaveLength(1)
  expect(fixture.unexpected).toEqual([])
})

test('窄屏导航支持 Escape、遮罩关闭和选择页面后关闭，焦点回到入口', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 700 })
  await mockAdmin(page)
  await page.goto('/')
  const opener = page.getByRole('button', { name: '打开导航' })
  await opener.click()
  const menu = page.getByRole('dialog', { name: 'LLM Proxy', exact: true })
  await expect(menu.getByText('admin', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).not.toBeVisible()
  await expect(opener).toBeFocused()
  await opener.click()
  await page.mouse.click(370, 350)
  await expect(menu).not.toBeVisible()
  await expect(opener).toBeFocused()
  await opener.click()
  await menu.getByRole('link', { name: '用户', exact: true }).click()
  await expect(page).toHaveURL(/\/users$/)
  await expect(menu).not.toBeVisible()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('用户')
  await opener.click()
  const account = menu.getByRole('button', { name: 'admin 的账户菜单', exact: true })
  await account.click()
  const accountMenu = page.getByRole('menu', { name: '账户菜单', exact: true })
  await expect(accountMenu).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(accountMenu).not.toBeVisible()
  await expect(menu).toBeVisible()
  await expect(account).toBeFocused()
  await menu.getByRole('button', { name: '切换主题' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.setViewportSize({ width: 901, height: 900 })
  await expect(menu).not.toBeVisible()
  const sidebar = page.getByRole('complementary', { name: '侧边栏' })
  await expect(sidebar).toHaveCSS('width', '72px')
  await expect(page.getByRole('navigation', { name: '主导航' })).toHaveCount(1)
  await sidebar.getByRole('button', { name: '展开侧栏' }).click()
  await page.setViewportSize({ width: 900, height: 900 })
  await expect(opener).toBeVisible()
  await expect(menu).not.toBeVisible()
  await page.setViewportSize({ width: 901, height: 900 })
  await expect(sidebar).toHaveCSS('width', '72px')
  await page.setViewportSize({ width: 900, height: 900 })
  await opener.click()
  await expect(menu).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 900 })
  await expect(menu).not.toBeVisible()
  await expect(sidebar).toHaveCSS('width', '216px')
  await expect(page.getByRole('navigation', { name: '主导航' })).toHaveCount(1)
  await expect(page.getByRole('link', { name: '用户', exact: true })).toHaveAttribute(
    'aria-current',
    'page',
  )
})

test('低高度窗口中菜单独立滚动，底部账户菜单始终可用', async ({ page }) => {
  const fixture = await mockAdmin(page)
  await page.setViewportSize({ width: 390, height: 420 })
  await page.goto('/')
  await page.getByRole('button', { name: '打开导航' }).click()
  const menu = page.getByRole('dialog')
  const account = menu.getByRole('button', { name: 'admin 的账户菜单', exact: true })
  const box = (await account.boundingBox())!
  expect(box.y).toBeGreaterThan(0)
  expect(box.y + box.height).toBeLessThanOrEqual(420)
  await menu.getByRole('link', { name: '设置', exact: true }).scrollIntoViewIfNeeded()
  await expect(account).toBeVisible()
  await account.click()
  const accountMenu = page.getByRole('menu', { name: '账户菜单', exact: true })
  const menuBox = (await accountMenu.boundingBox())!
  expect(menuBox.y).toBeGreaterThanOrEqual(0)
  expect(menuBox.y + menuBox.height).toBeLessThanOrEqual(box.y)
  await accountMenu.getByRole('menuitem', { name: '退出登录' }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect(fixture.unexpected).toEqual([])
})

test('账户菜单支持键盘操作、点击外部关闭和退出失败后重试', async ({ page }) => {
  const fixture = await mockAdmin(page)
  fixture.bootstrap.username = 'administrator-with-a-long-display-name'
  let attempts = 0
  await page.route('**/api/logout', async (route) => {
    attempts += 1
    if (attempts === 1) {
      await route.fulfill({ status: 500, json: { error: 'Temporary logout failure' } })
    } else await route.fallback()
  })
  await page.goto('/')
  const account = page.getByRole('button', { name: `${fixture.bootstrap.username} 的账户菜单` })
  const theme = page.getByRole('button', { name: '切换主题' })
  const accountBox = (await account.boundingBox())!
  const themeBox = (await theme.boundingBox())!
  expect(accountBox.x + accountBox.width).toBeLessThanOrEqual(themeBox.x)
  await account.focus()
  await page.keyboard.press('Enter')
  const menu = page.getByRole('menu', { name: '账户菜单', exact: true })
  await expect(menu).toBeVisible()
  await page.getByRole('heading', { level: 1 }).click()
  await expect(menu).not.toBeVisible()
  expect(attempts).toBe(0)
  await account.focus()
  await page.keyboard.press('ArrowDown')
  const logout = menu.getByRole('menuitem', { name: '退出登录' })
  await expect(logout).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('.ui-toast')).toContainText('Temporary logout failure')
  await expect(account).toBeVisible()
  await expect(page).not.toHaveURL(/\/login$/)
  await account.click()
  await logout.click()
  await expect(page).toHaveURL(/\/login$/)
  expect(attempts).toBe(2)
  expect(fixture.unexpected).toEqual([])
})
