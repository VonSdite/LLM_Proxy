import { expect, test } from '../browser-test'
import { mockAdmin } from '../browser-fixtures'

test('Agent 页签排序、显隐、刷新恢复和保留至少一项', async ({ page }) => {
  await mockAdmin(page)
  await page.goto('/agents')
  const tabs = page.getByRole('tablist', { name: 'Agent 类型' })
  await page.getByRole('button', { name: '设置 Agent 页签', exact: true }).click()
  const list = page.getByRole('list', { name: 'Agent 页签顺序' })
  const popup = page.getByRole('dialog', { name: 'Agent 页签', exact: true })
  const before = await popup.boundingBox()
  await list.getByRole('button', { name: '拖动第 2 项', exact: true }).press('Home')
  await page.getByRole('switch', { name: '显示 Claude', exact: true }).click()
  await page.getByRole('switch', { name: '显示 Opencode v1', exact: true }).click()
  await expect(page.getByRole('switch', { name: '显示 Codex', exact: true })).toBeDisabled()
  await expect(page.locator('[role="tablist"] [role="tab"]')).toHaveText([
    'Claude',
    'Codex',
    'Opencode v1',
  ])
  const after = await popup.boundingBox()
  expect(Math.abs(after!.x - before!.x)).toBeLessThan(1)
  expect(Math.abs(after!.y - before!.y)).toBeLessThan(1)
  await expect(popup).not.toContainText('拖动排序，至少保留一项')
  await popup.getByRole('button', { name: '保存', exact: true }).click()
  await expect(tabs.getByRole('tab')).toHaveText(['Codex'])
  await expect(tabs.getByRole('tab', { name: 'Codex' })).toHaveAttribute('aria-selected', 'true')
  await page.reload()
  await expect(tabs.getByRole('tab')).toHaveText(['Codex'])
  await page.getByRole('button', { name: '设置 Agent 页签', exact: true }).click()
  await expect(list.getByRole('listitem').first()).toContainText('Codex')
  await page.getByRole('button', { name: '恢复默认', exact: true }).click()
  await popup.getByRole('button', { name: '保存', exact: true }).click()
  await expect(tabs.getByRole('tab')).toHaveText(['Claude', 'Codex', 'Opencode v1'])
})

test('Agent 页签弹窗取消放弃，未保存变化由共享确认弹窗保护', async ({ page }) => {
  await mockAdmin(page)
  await page.goto('/agents')
  const open = page.getByRole('button', { name: '设置 Agent 页签', exact: true })
  const dialog = page.getByRole('dialog', { name: 'Agent 页签', exact: true })
  await open.click()
  await dialog.getByRole('switch', { name: '显示 Claude', exact: true }).click()
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await open.click()
  await expect(dialog.getByRole('switch', { name: '显示 Claude', exact: true })).toBeChecked()
  await dialog.getByRole('switch', { name: '显示 Claude', exact: true }).click()
  await page.keyboard.press('Escape')
  const prompt = page.getByRole('dialog', { name: '保存修改？', exact: true })
  await expect(prompt).toBeVisible()
  await prompt.getByRole('button', { name: '继续编辑', exact: true }).click()
  await dialog.getByRole('switch', { name: '显示 Claude', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(prompt).toHaveCount(0)
  await open.click()
  await dialog.getByRole('switch', { name: '显示 Claude', exact: true }).click()
  await page.mouse.click(10, 10)
  await expect(prompt).toBeVisible()
  await prompt.getByRole('button', { name: '保存并关闭', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('tab', { name: 'Claude', exact: true })).toHaveCount(0)
})
