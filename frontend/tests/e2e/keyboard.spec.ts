import { expect, test } from '../browser-test'
import { mockAdmin } from '../browser-fixtures'

test('共享选择框支持方向键、Enter 和 Escape，开关支持空格', async ({ page }) => {
  await mockAdmin(page)
  await page.goto('/dev/components')
  const select = page.getByRole('combobox', { name: '固定选项', exact: true })
  await select.focus()
  await select.press('ArrowDown')
  await expect(page.getByRole('listbox')).toBeVisible()
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(select).toContainText('Codex')
  await expect(select).toBeFocused()
  await select.press('Enter')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('listbox')).toHaveCount(0)
  await expect(select).toBeFocused()

  const search = page.getByRole('combobox', { name: '搜索候选', exact: true })
  await search.fill('cod')
  await search.press('ArrowDown')
  await search.press('Enter')
  await expect(search).toHaveValue('codex')
  await expect(search).toBeFocused()
  await expect(page.getByRole('listbox')).toHaveCount(0)

  const toggle = page.getByRole('switch', { name: '功能开关', exact: true })
  await toggle.focus()
  await toggle.press('Space')
  await expect(toggle).not.toBeChecked()
})

test('字段帮助支持聚焦与 Escape，弹窗约束并恢复键盘焦点', async ({ page }) => {
  await mockAdmin(page)
  await page.goto('/dev/components')
  const help = page.getByRole('button', { name: '模型 ID说明', exact: true })
  await help.focus()
  const content = page.locator('.ui-help-content')
  await expect(content).toBeVisible()
  expect(await help.getAttribute('aria-describedby')).toBe(await content.getAttribute('id'))
  await help.press('Escape')
  await expect(content).toHaveCount(0)
  await expect(help).toBeFocused()

  await page.goto('/')
  const trigger = page.getByRole('button', { name: '新增 Provider', exact: true })
  await trigger.focus()
  await trigger.press('Enter')
  const dialog = page.getByRole('dialog')
  const close = dialog.getByRole('button', { name: '关闭', exact: true })
  await close.focus()
  await close.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
})

test('表格列宽支持键盘调整并在刷新后保留', async ({ page }) => {
  await mockAdmin(page)
  await page.goto('/dev/components')
  const handle = page.getByRole('separator', { name: '调整模型列宽', exact: true })
  const initial = Number(await handle.getAttribute('aria-valuenow'))
  await handle.focus()
  await handle.press('ArrowRight')
  await expect(handle).toHaveAttribute('aria-valuenow', String(initial + 16))
  await page.reload()
  await expect(handle).toHaveAttribute('aria-valuenow', String(initial + 16))
  await handle.focus()
  await handle.press('ArrowLeft')
  await expect(handle).toHaveAttribute('aria-valuenow', String(initial))
})

test('统计多选标题关联按钮，键盘选择筛选并提交完整模型 ID', async ({ page }) => {
  const fixture = await mockAdmin(page)
  await page.goto('/statistics')
  const trigger = page.getByRole('button', { name: '请求模型', exact: true })
  await page.getByText('请求模型', { exact: true }).click()
  await expect(page.getByRole('textbox', { name: '搜索选项' })).toBeFocused()
  await page.getByRole('textbox', { name: '搜索选项' }).fill('smart')
  const option = page.getByRole('checkbox', { name: 'smart', exact: true })
  await option.focus()
  await option.press('Space')
  await expect(option).toBeChecked()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await expect(trigger).toContainText('smart')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect
    .poll(() => fixture.calls.filter((call) => call.path === '/api/statistics').at(-1)?.url)
    .toContain('request_model=smart')
  expect(fixture.unexpected).toEqual([])
})
